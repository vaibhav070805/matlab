clc;
close all;
clear all;
fs=10;
n=0:1/fs:10;
N=50;
a0=0.42;a2=0.08;a1=0.5;
h_lp_ideal=sin(2*pi*fs*(n-(N/2))/(pi*(n-N/2)));
w_ham=0.54-0.46*cos(2*pi*n/N);
w_han=0.5*(1-cos(2*pi*n/N));
w_black=a0-a1*cos(2*pi*n/N)+a2*cos(4*pi*n/N);
y1=h_lp_ideal.*w_black;
y2=h_lp_ideal.*w_ham;
y3=h_lp_ideal.*w_han;
Y1=fft(y1);Y2=fft(y2);Y3=fft(y3);
figure;
subplot(3,1,1);
plot(abs(Y1));
subplot(3,1,2);
plot(abs(Y2));
subplot(3,1,3);
plot(abs(Y3));
