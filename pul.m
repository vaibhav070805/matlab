t = -5 : 0.01 : 5;
pulse = rectangularPulse(-1, 1, t);
figure;
plot(t, pulse, 'LineWidth', 2);
title('1. Signal in Time (Rectangular Pulse)');
xlabel('Time (seconds)'); ylabel('Amplitude');
grid on; ylim([-0.5, 1.5]);
raw_fft = fft(pulse);               
centered_fft = fftshift(raw_fft); 
frequency_axis = (-length(t)/2 : length(t)/2 - 1) * (100 / length(t));
figure;
plot(frequency_axis, abs(centered_fft) / 100, 'LineWidth', 2); 
title('2. Signal in Frequency (Sinc Shape)');
xlabel('Frequency (Hz)'); ylabel('Strength');
grid on; xlim([-5, 5]);                   
lpf_mask = abs(frequency_axis) <= 0.5;           
filtered_s_f = centered_fft .* lpf_mask;
figure;
plot(frequency_axis, abs(filtered_s_f) / 100, 'LineWidth', 2);
title('3. LPF Applied Directly in Frequency Domain (After FFT)');
xlabel('Frequency (Hz)'); ylabel('Strength');
xlim([-3, 3]); grid on;
fc = 2;
left_shift  = interp1(frequency_axis, filtered_s_f, frequency_axis + fc, 'linear', 0);
right_shift = interp1(frequency_axis, filtered_s_f, frequency_axis - fc, 'linear', 0);
modulated_s_f = 0.5 * (left_shift + right_shift);
figure;
plot(frequency_axis, abs(modulated_s_f) / 100,  'LineWidth', 2); % Fixed Fs to 100
title('4. Modulation Performed Entirely in Frequency Domain');
xlabel('Frequency (Hz)'); ylabel('Strength');
grid on; xlim([-5, 5]);